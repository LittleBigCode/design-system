#!/usr/bin/env node
// Batch 16 (#49), direction.md decisions 8-9: the HTML tab's markup, derived
// from the real rendered DOM so it cannot drift from the React tab.
//
// Why a browser and not a Node SSR render: this repo's root package and
// `site/` each install their own `react`/`react-dom` copies (root's package
// is consumed via a `file:..` symlink), and only the *client* bundle's
// `resolve.dedupe` unifies them onto one instance. Every Node-side render
// path (Vite's `ssrLoadModule`, `ssr.noExternal`, a rolldown bundle with
// `resolve.alias`) ends up executing two different React instances for the
// same tree and crashes on the first hook. A real browser never has this
// problem — it only ever sees the one, already-deduped client bundle — so
// this drives the actual docs app with Playwright and scrapes the DOM the
// same way a person's eyes would, instead of re-rendering anything.
//
// Output: site/src/registry/demo-markup.json, keyed like every other demo
// artefact (`<slug>/<demo-name>`), read by plugins/demo-source.ts. Not
// committed (see .gitignore) — regenerated by `npm run build` at the repo
// root before `site/`'s own build runs.

import { preview } from "vite"
import { chromium } from "playwright"
import fs from "node:fs/promises"
import path from "node:path"

import { UTILITY_MAP } from "../plugins/utility-mapping.ts"
import { resolveViaTailwind } from "../plugins/resolve-tailwind-class.ts"

const SITE_ROOT = path.resolve(import.meta.dirname, "..")
const DEMOS_DIR = path.join(SITE_ROOT, "src/registry/demos")
const OUT_FILE = path.join(SITE_ROOT, "src/registry/demo-markup.json")

/** Every top-level demo folder is a route (`/docs/<slug>`) — see demo-source.ts's landedSlugs(). */
async function slugs() {
  const entries = await fs.readdir(DEMOS_DIR, { withFileTypes: true })
  return entries.filter((e) => e.isDirectory()).map((e) => e.name)
}

/**
 * Rewrites one scraped element's outer HTML onto `.ds-*` (utility-mapping.md):
 * every space-separated class token that isn't already a `ds-*` class (this
 * package's own convention, components and utilities alike — direction.md
 * decision 7) is a Tailwind wrapper class from the demo's own JSX. Mapped
 * ones swap in place; unmapped ones resolve through Tailwind's own compiler
 * (`resolveViaTailwind`) to a real inline declaration rather than being left
 * as a dead class name a buildless consumer's stylesheet can't style.
 *
 * `data-demo-key` and every React-internal `data-slot`/ARIA attribute the
 * component itself renders survive untouched — those are exactly "the
 * classes and ARIA a consumer should render" (decision 9), not Tailwind.
 */
async function codemod(html, warn) {
  const classAttr = /\bclass="([^"]*)"/g
  let unresolved = []
  let out = ""
  let last = 0
  let match
  while ((match = classAttr.exec(html))) {
    out += html.slice(last, match.index)
    last = match.index + match[0].length
    const tokens = match[1].split(/\s+/).filter(Boolean)
    const kept = []
    const styles = []
    for (const token of tokens) {
      if (token === "" || token.startsWith("ds-")) {
        kept.push(token)
        continue
      }
      const mapped = UTILITY_MAP[token]
      if (mapped) {
        kept.push(mapped)
        continue
      }
      const resolution = await resolveViaTailwind(token)
      switch (resolution.kind) {
        case "style":
          styles.push(resolution.declaration)
          break
        case "ignore":
          // Not Tailwind's: a third-party class (recharts-*, rdp-*) or a demo's
          // own ad hoc hook (is-active) — neither is this codemod's to style.
          kept.push(token)
          break
        case "drop":
          // Interactive/responsive state (hover:, group-*, data-*:, an
          // arbitrary value) — decision 9's "markup, not behaviour" has no
          // static rendering of this anyway.
          break
        case "unresolved":
          unresolved.push(token)
          break
      }
    }
    let attr = `class="${kept.join(" ")}"`
    if (styles.length) attr += ` style="${styles.join("; ")}"`
    out += attr
  }
  out += html.slice(last)
  if (unresolved.length) warn(unresolved)
  return out
}

async function main() {
  // Against the real production build (`vite preview`), not the dev server:
  // `base` and asset URLs are exactly what a consumer's browser gets, and
  // matches how this repo's own `test:visual`/`test:a11y` already run —
  // playwright.config.ts's own comment says why. Requires `vite build` to
  // have already produced `dist/` (this script's own npm script runs it
  // first — see site/package.json).
  const server = await preview({
    root: SITE_ROOT,
    preview: { port: 0 },
    logLevel: "warn",
  })
  const base = server.resolvedUrls?.local[0]
  if (!base) throw new Error("[build-demo-markup] vite preview did not resolve a URL")

  const browser = await chromium.launch()
  const page = await browser.newPage()

  const manifest = {}
  const allUnresolved = new Set()

  for (const slug of await slugs()) {
    const url = new URL(`docs/${slug}`, base).href
    await page.goto(url, { waitUntil: "networkidle" })
    const nodes = await page.$$("[data-demo-key]")
    for (const node of nodes) {
      const key = await node.getAttribute("data-demo-key")
      const html = await node.innerHTML()
      manifest[key] = (
        await codemod(html, (tokens) => tokens.forEach((t) => allUnresolved.add(t)))
      ).trim()
    }
  }

  await browser.close()
  await server.close()

  if (allUnresolved.size) {
    throw new Error(
      `[build-demo-markup] ${allUnresolved.size} Tailwind class(es) have no ` +
        `.ds-* mapping and Tailwind's own compiler couldn't resolve them to a ` +
        `static declaration (a variant or arbitrary-value class, most likely):\n` +
        `  ${[...allUnresolved].sort().join("\n  ")}\n` +
        `Add a mapping to utility-mapping.md/plugins/utility-mapping.ts, or ` +
        `change the demo's wrapper class — a dead, unstyled class in a ` +
        `"buildless" markup tab is the failure this batch's own headline claim exists to catch.`
    )
  }

  await fs.writeFile(OUT_FILE, JSON.stringify(manifest, null, 2) + "\n")
  console.log(`[build-demo-markup] wrote ${Object.keys(manifest).length} entries to ${path.relative(SITE_ROOT, OUT_FILE)}`)
}

main()
